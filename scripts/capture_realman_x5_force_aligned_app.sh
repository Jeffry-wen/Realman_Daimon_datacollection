  GRIPPER_COMMAND_SOURCE=program
  export TRAJECTORY_GRIPPER_CONTROL_ENABLED=true
  export SEND_ACTION_ENABLED=false
  export SEND_GRIPPER_ACTION_ENABLED=true
  export GRIPPER_PREWARM_ON_EPISODE_START=false
elif [[ "${CAPTURE_CONTROL_MODE}" == "leader" ]]; then
  GRIPPER_COMMAND_SOURCE=leader
  export TRAJECTORY_GRIPPER_CONTROL_ENABLED=false
  export SEND_ACTION_ENABLED="${SEND_ACTION_ENABLED:-false}"
  export SEND_GRIPPER_ACTION_ENABLED="${SEND_GRIPPER_ACTION_ENABLED:-true}"
