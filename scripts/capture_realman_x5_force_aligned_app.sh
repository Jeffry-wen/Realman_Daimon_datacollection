    CAPTURE_CONTROL_MODE="${GRIPPER_COMMAND_SOURCE}"
  elif [[ "${TRAJECTORY_GRIPPER_CONTROL_ENABLED,,}" =~ ^(1|true|yes|on)$ ]]; then
    CAPTURE_CONTROL_MODE=program
  else
    CAPTURE_CONTROL_MODE=leader
  fi
