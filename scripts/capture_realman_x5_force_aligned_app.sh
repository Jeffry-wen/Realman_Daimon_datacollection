export EPISODE_RETURN_TO_START_SPEED="${EPISODE_RETURN_TO_START_SPEED:-5}"
export EPISODE_RETURN_TO_START_TOLERANCE_DEG="${EPISODE_RETURN_TO_START_TOLERANCE_DEG:-0.5}"
export EPISODE_RETURN_TO_START_MAX_DELTA_DEG="${EPISODE_RETURN_TO_START_MAX_DELTA_DEG:-60}"
export EPISODE_RETURN_TO_START_TIMEOUT_S="${EPISODE_RETURN_TO_START_TIMEOUT_S:-60}"
export EPISODE_RETURN_TO_START_POLL_HZ="${EPISODE_RETURN_TO_START_POLL_HZ:-20}"
export EPISODE_RETURN_TO_START_STABLE_SAMPLES="${EPISODE_RETURN_TO_START_STABLE_SAMPLES:-3}"
