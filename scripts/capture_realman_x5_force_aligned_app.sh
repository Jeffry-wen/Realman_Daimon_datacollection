if [[ "${ALIGNED_FORCE_PER_SENSOR_TACTILE_CACHE,,}" =~ ^(1|true|yes|on)$ ]]; then
  export X5_TACTILE_ASYNC_CACHE_MODE="per_sensor_thread"
else
  export X5_TACTILE_ASYNC_CACHE_MODE="${X5_TACTILE_ASYNC_CACHE_MODE:-per_sensor_thread}"
fi
export X5_TACTILE_ASYNC_CACHE_FPS="${X5_TACTILE_ASYNC_CACHE_FPS:-120}"
export X5_TACTILE_ASYNC_CACHE_HISTORY_SECONDS="${X5_TACTILE_ASYNC_CACHE_HISTORY_SECONDS:-12}"
