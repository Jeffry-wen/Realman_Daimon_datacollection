export ALIGNED_PRESTART_STREAMING_ENCODERS="${ALIGNED_PRESTART_STREAMING_ENCODERS:-true}"
export ALIGNED_ENCODER_WARM_START="${ALIGNED_ENCODER_WARM_START:-true}"
export ALIGNED_ENCODER_WARM_START_TIMEOUT_S="${ALIGNED_ENCODER_WARM_START_TIMEOUT_S:-5.0}"
