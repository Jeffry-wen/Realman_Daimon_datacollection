export EPISODE_RIGHT_ARM_RESET_STOP_DRAG_FIRST="${EPISODE_RIGHT_ARM_RESET_STOP_DRAG_FIRST:-true}"
export EPISODE_RIGHT_ARM_RESET_PAUSE_READERS="${EPISODE_RIGHT_ARM_RESET_PAUSE_READERS:-true}"
